// 根据城市代码获取城市名称
export const getCityNameByCode = (cityCode) => {
	const city = selectorObjAab302.find(item => item.value === cityCode);
	return city ? city.title : '';
};

// 根据县区代码获取县区名称
export const getCountyNameByCode = (countyCode, cityCode) => {
	const counties = cityCountyData[cityCode] || [];
	const county = counties.find(item => item.value === countyCode);
	return county ? county.title : '';
};